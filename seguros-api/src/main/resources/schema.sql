CREATE TABLE poliza (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    meses_vigencia INT NOT NULL,
    canon_mensual DECIMAL(19, 2) NOT NULL,
    prima DECIMAL(19, 2) NOT NULL
);

CREATE TABLE riesgo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poliza_id BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    identificador_inmueble VARCHAR(100) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    canon_mensual DECIMAL(19, 2) NOT NULL,
    prima DECIMAL(19, 2) NOT NULL,
    CONSTRAINT fk_riesgo_poliza FOREIGN KEY (poliza_id) REFERENCES poliza (id)
);
